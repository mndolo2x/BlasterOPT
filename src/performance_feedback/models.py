"""
Data Models and Pydantic Schemas for Blast Performance Feedback Loop.

Defines schemas for blast records, prediction snapshots, actual observations,
predicted-vs-actual comparison results, dataset review status, and export manifests.
"""

from datetime import datetime, timezone
import hashlib
import json
from typing import Dict, Any, List, Optional, Union, Literal
from pydantic import BaseModel, Field


def _utc_now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


class BlastRecord(BaseModel):
    """
    Core identifiable blast record for open-pit or underground operations.
    """
    blast_id: str = Field(..., description="Unique immutable blast identifier")
    site_id: str = Field("Jwaneng", description="Mine or site name (e.g., Jwaneng, Orapa, Morupule)")
    operation_type: Literal["open_pit", "underground"] = Field("open_pit", description="Type of mining operation")
    location_identifier: str = Field(..., description="Pit/Bench/Stope/Level/Excavation ID")
    blast_date: str = Field(default_factory=_utc_now_iso, description="ISO blast execution timestamp")
    created_at: str = Field(default_factory=_utc_now_iso, description="Record creation timestamp")
    engineer_id: Optional[str] = Field("ENGINEER_BW_01", description="Responsible engineer or team ID")
    status: Literal["PLANNED", "EXECUTED", "MEASURED", "REVIEWED", "ARCHIVED"] = Field(
        "PLANNED", description="Lifecycle status"
    )
    design_id: Optional[str] = Field(None, description="Linked blast design ID")
    design_version: Optional[int] = Field(None, description="Linked blast design version number")
    planned_params: Dict[str, Any] = Field(default_factory=dict, description="Snapshot of planned design parameters")
    geological_context: Dict[str, Any] = Field(default_factory=dict, description="Rock type, lithology, domain, RMR, UCS")
    notes: Optional[str] = Field(None, description="Operational notes or observations")

    def update_snapshot(self, **kwargs) -> "BlastRecord":
        """Returns updated BlastRecord copy."""
        data = self.model_dump() if hasattr(self, "model_dump") else self.dict()
        data.update(kwargs)
        return BlastRecord(**data)


class PredictionSnapshot(BaseModel):
    """
    Immutable historical snapshot of an original prediction run generated by a BlastOPT model.
    """
    prediction_run_id: str = Field(..., description="Unique prediction run identifier")
    blast_id: str = Field(..., description="Associated blast ID")
    prediction_timestamp: str = Field(default_factory=_utc_now_iso, description="ISO timestamp of prediction run")
    model_name: str = Field(..., description="Model key or display name")
    model_version: str = Field("v1.0", description="Model version code")
    training_dataset_ref: Optional[str] = Field(None, description="Fingerprint or reference ID of model's training dataset")
    target_metric: str = Field(..., description="Target outcome variable name (e.g. d50_mm, ppv_mms, airblast_db, flyrock_m, cost_per_tonne_usd, rock_class)")
    predicted_value: float = Field(..., description="Predicted numerical value")
    unit: str = Field(..., description="Measurement unit (e.g. mm, mm/s, dB, m, $/t)")
    input_features_snapshot: Dict[str, Any] = Field(default_factory=dict, description="Reproducible snapshot of input feature values")
    uncertainty_bounds: Optional[Dict[str, float]] = Field(None, description="95% confidence bounds (e.g. {'lower_95': ..., 'upper_95': ...})")
    warnings: List[str] = Field(default_factory=list, description="Applicable model or domain warnings")
    site_config_version: Optional[str] = Field("v1.0", description="Site configuration version at prediction time")
    provenance: Optional[str] = Field("BlastOPT Model Engine", description="Source or pipeline provenance string")


class ActualMeasurement(BaseModel):
    """
    Measured post-blast field observation.
    """
    measurement_id: str = Field(..., description="Unique measurement ID")
    blast_id: str = Field(..., description="Associated blast ID")
    measurement_timestamp: str = Field(default_factory=_utc_now_iso, description="ISO timestamp of field measurement")
    target_metric: str = Field(..., description="Measured outcome metric (e.g. d50_mm, ppv_mms, airblast_db, flyrock_m, cost_per_tonne_usd, rock_class)")
    measured_value: Union[float, str] = Field(..., description="Numerical or categorical actual value")
    unit: str = Field(..., description="Measurement unit")
    measurement_method: Optional[str] = Field("Field Sensor / UAV", description="Method or instrument used")
    instrument_id: Optional[str] = Field(None, description="Sensor or camera serial ID")
    sensor_distance_m: Optional[float] = Field(None, description="Distance from blast location to sensor (m)")
    source_filename: Optional[str] = Field(None, description="Uploaded file name")
    raw_attributes: Dict[str, Any] = Field(default_factory=dict, description="Additional MWD or survey metadata")


class ComparisonResult(BaseModel):
    """
    Calculated comparison between an original prediction snapshot and a measured actual observation.
    """
    comparison_id: str = Field(..., description="Unique comparison identifier")
    blast_id: str = Field(..., description="Associated blast ID")
    prediction_run_id: str = Field(..., description="Source prediction snapshot ID")
    measurement_id: str = Field(..., description="Source actual measurement ID")
    target_metric: str = Field(..., description="Target metric name")
    predicted_value: float = Field(..., description="Original predicted value")
    measured_value: float = Field(..., description="Measured actual value")
    signed_error: float = Field(..., description="Signed error e_i = predicted - measured")
    absolute_error: float = Field(..., description="Absolute error |e_i|")
    percentage_error: Optional[float] = Field(None, description="Absolute percentage error (|e_i| / |measured|) * 100")
    unit: str = Field(..., description="Measurement unit")
    model_name: str = Field(..., description="Model key or display name")
    model_version: str = Field("v1.0", description="Model version")
    compared_at: str = Field(default_factory=_utc_now_iso, description="Timestamp of comparison calculation")


class DatasetReviewRecord(BaseModel):
    """
    Review and approval status for a candidate historical blast record.
    """
    review_id: str = Field(..., description="Unique review identifier")
    blast_id: str = Field(..., description="Associated blast ID")
    target_metric: str = Field(..., description="Target metric under review")
    status: Literal["Uploaded", "Validated", "Awaiting Review", "Approved", "Rejected"] = Field(
        "Awaiting Review", description="Review workflow status"
    )
    inclusion_status: bool = Field(False, description="Whether record is approved for model training")
    exclusion_reason: Optional[str] = Field(None, description="Reason if rejected or excluded")
    reviewer_id: Optional[str] = Field("ENGINEER_REVIEWER", description="User ID of authorized reviewer")
    review_timestamp: Optional[str] = Field(None, description="Timestamp of review decision")
    comments: Optional[str] = Field(None, description="Reviewer notes")


class ExportManifest(BaseModel):
    """
    Provenance manifest accompanying an exported training dataset.
    """
    export_id: str = Field(..., description="Unique export manifest ID")
    export_timestamp: str = Field(default_factory=_utc_now_iso, description="Export timestamp")
    dataset_version: str = Field("v1.0.0", description="Exported dataset semantic version")
    target_metric: str = Field(..., description="Target metric for training")
    included_blast_ids: List[str] = Field(default_factory=list, description="List of approved blast IDs included")
    approved_record_count: int = Field(..., description="Total approved rows exported")
    feature_schema: List[str] = Field(default_factory=list, description="Input feature column names")
    unit_definitions: Dict[str, str] = Field(default_factory=dict, description="Feature and target units mapping")
    filters_applied: Dict[str, Any] = Field(default_factory=dict, description="Filters used when generating export")
    manifest_hash: str = Field(..., description="SHA-256 cryptographic hash of exported CSV contents")

    @classmethod
    def compute_hash(cls, csv_content_bytes: bytes) -> str:
        return hashlib.sha256(csv_content_bytes).hexdigest()
